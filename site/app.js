(() => {
  'use strict';
  const root = document.getElementById('dp-design');
  const { config, dates, digests, demo } = JSON.parse(document.getElementById('daily-paper-data').textContent);
  const FRONTIERS = 'optimization-frontiers';
  const byDate = new Map(digests.map(d => [d.date, d]));
  const results = root.querySelector('#dp-results');
  const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const paperElementId = id => `paper-${id.replace(/[^a-zA-Z0-9_-]/g, '-')}`;
  const formatted = (date, options) => new Intl.DateTimeFormat('en-US', { ...options, timeZone: 'UTC' }).format(new Date(`${date}T12:00:00Z`));
  const longDate = date => formatted(date, { year: 'numeric', month: 'long', day: 'numeric' });
  const state = { date: dates[0], direction: 'all', expired: false };
  document.title = config.title;
  root.querySelector('.dp-brand').innerHTML = `${escape(config.title)}<span class="dp-brand-dot">.</span>`;
  root.querySelector('.dp-preview').hidden = !demo;
  root.querySelector('.dp-archive').href = config.archive_url;
  root.querySelector('#dp-window-label').textContent = `The latest ${config.display_days} days`;
  root.querySelector('.dp-footer').textContent = `${longDate(dates.at(-1))} – ${longDate(dates[0])}`;

  function visibleDirections(papers) {
    const used = new Set(papers.flatMap(p => p.directions));
    return [{ id: 'all', name: 'All directions' }, ...config.directions.filter(d => d.id === FRONTIERS || used.has(d.id))];
  }
  function readLocation() {
    const params = new URLSearchParams(location.hash.slice(1));
    const requested = params.get('date');
    state.expired = Boolean(requested && !dates.includes(requested));
    state.date = dates.includes(requested) ? requested : dates[0];
    state.direction = params.get('direction') || 'all';
    render();
  }
  function saveLocation() {
    const params = new URLSearchParams({ date: state.date });
    if (state.direction !== 'all') params.set('direction', state.direction);
    history.replaceState(null, '', `#${params}`);
  }
  function empty(title, body) {
    return `<div class="dp-empty"><strong>${escape(title)}</strong>${body ? `<p>${escape(body)}</p>` : ''}</div>`;
  }
  function card(paper, index) {
    const tags = config.directions.filter(d => paper.directions.includes(d.id)).map(d => `<span class="dp-tag ${d.id === FRONTIERS ? 'dp-tag-front' : ''}">${escape(d.name)}</span>`).join('');
    const highlights = [['field', '前沿亮点'], ['group', '课题相关亮点']].filter(([type]) => paper.highlight_types.includes(type)).map(([type, label]) => `<span class="dp-tag dp-tag-highlight dp-highlight-${type}" lang="zh-CN">${label}</span>`).join('');
    // html fields are generated by the build from escaped text and trusted KaTeX output.
    return `<article class="dp-paper" id="${paperElementId(paper.arxiv_id)}" aria-label="${escape(paper.title)}">
      <div class="dp-kicker"><span class="dp-number">${String(index + 1).padStart(2, '0')}</span><div class="dp-tags">${highlights}${tags}</div></div>
      <h3>${paper.html.title}</h3>
      <p class="dp-authors">${escape(paper.authors.join(', '))}</p>
      <p class="dp-dates">Submitted ${escape(paper.submitted)} · Updated ${escape(paper.updated)} · v${paper.version}</p>
      <span class="dp-guide-label">SUMMARY</span>
      <div class="dp-abstract" lang="zh-CN">${paper.html.summary}</div>
      <div class="dp-reason" lang="zh-CN"><strong>推荐理由</strong>　<span>${paper.html.reason}</span></div>
      ${paper.html.update_note ? `<div class="dp-update" lang="zh-CN"><strong>Update</strong> · ${paper.html.update_note}</div>` : ''}
      <details class="dp-original"><summary>Abstract</summary><div class="dp-original-text" lang="en">${paper.html.abstract}</div></details>
      <div class="dp-actions">${demo ? '<span class="dp-meta">Illustrative paper · No source link</span>' : `<a class="dp-source" href="https://arxiv.org/abs/${escape(paper.arxiv_id)}v${paper.version}" target="_blank" rel="noopener noreferrer">Read on arXiv ↗</a>`}</div>
    </article>`;
  }
  function render() {
    const digest = byDate.get(state.date);
    const papers = digest?.papers || [];
    const directions = visibleDirections(papers);
    if (!directions.some(d => d.id === state.direction)) state.direction = 'all';
    root.querySelector('.dp-directions').innerHTML = directions.map(d => `<button type="button" class="dp-direction ${d.id === FRONTIERS ? 'dp-frontier' : ''}" data-direction="${d.id}" aria-pressed="${d.id === state.direction}"><span>${escape(d.name)}</span><small>${d.id === 'all' ? papers.length : papers.filter(p => p.directions.includes(d.id)).length}</small></button>`).join('');
    root.querySelector('.dp-mobile-direction').innerHTML = directions.map(d => `<option value="${d.id}" ${d.id === state.direction ? 'selected' : ''}>${escape(d.name)}</option>`).join('');
    root.querySelector('.dp-datebar').innerHTML = dates.map(d => `<button type="button" class="dp-date" data-date="${d}" aria-label="${longDate(d)}" aria-pressed="${!state.expired && state.date === d}"><span>${formatted(d, { weekday: 'short' })}</span><b>${d.slice(-2)}</b></button>`).join('');
    root.querySelector('#dp-date-title').textContent = state.expired ? 'Digest unavailable' : longDate(state.date);
    root.querySelector('#dp-status').textContent = state.expired ? '' : !digest ? 'Not available' : digest.status === 'incomplete' ? 'Retrieval incomplete' : 'Updated';
    if (state.expired) { results.innerHTML = empty('This date is outside the current reading window', 'Use Archive on GitHub for earlier digests, or select a recent date.'); return; }
    if (!digest) { results.innerHTML = empty('No digest available for this date', 'A recommendation result has not been published.'); return; }
    let notice = digest.status === 'incomplete' ? empty('Retrieval is incomplete', 'The available recommendations are verified; screening for this date is not yet complete.') : '';
    if (['all', FRONTIERS].includes(state.direction)) {
      if (digest.frontiers_status === 'no_matches') notice += '<p class="dp-frontier-status"><strong>Optimization Frontiers</strong> · No suitable papers today.</p>';
      if (digest.frontiers_status === 'incomplete') notice += '<p class="dp-frontier-status"><strong>Optimization Frontiers</strong> · Screening incomplete.</p>';
    }
    const filtered = papers.filter(p => state.direction === 'all' || p.directions.includes(state.direction));
    if (!filtered.length) {
      results.innerHTML = notice + (state.direction === 'all' && digest.status === 'complete' ? empty('No suitable papers today', '') : '');
      return;
    }
    const buckets = [[], [], []];
    for (const paper of filtered) buckets[paper.highlight_types.includes('field') ? 0 : paper.highlight_types.includes('group') ? 1 : 2].push(paper);
    const labels = ['前沿亮点', '课题相关亮点', '剩余推荐'];
    let index = 0;
    results.innerHTML = notice + buckets.map((items, bucket) => items.length ? `<section class="dp-paper-group" aria-labelledby="dp-group-${bucket}"><div class="dp-summary-line"><h2 id="dp-group-${bucket}" lang="zh-CN">${labels[bucket]}</h2><span>${items.length} 篇</span></div>${items.map(paper => card(paper, index++)).join('')}</section>` : '').join('');
  }
  root.addEventListener('click', event => {
    const button = event.target.closest('button');
    if (!button || !root.contains(button)) return;
    const direction = button.dataset.direction, date = button.dataset.date;
    if (!direction && !date) return;
    state.expired = false;
    if (direction) state.direction = direction;
    if (date) state.date = date;
    render(); saveLocation();
    root.querySelector(direction ? `[data-direction="${state.direction}"]` : `[data-date="${state.date}"]`)?.focus();
  });
  root.querySelector('.dp-mobile-direction').addEventListener('change', event => {
    state.direction = event.target.value; state.expired = false; render(); saveLocation();
  });
  window.addEventListener('hashchange', readLocation);
  readLocation();
})();
